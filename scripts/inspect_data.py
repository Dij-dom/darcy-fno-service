"""Read-only inspection of the PDEBench 2D Darcy flow HDF5 file.

Reports every group/dataset (shape, dtype, chunking, attributes), value statistics,
distinct values (overall and per sample), and coordinate grids. Large arrays are read
in chunks along the first axis so memory use stays bounded.

Usage:
    python scripts/inspect_data.py [path.hdf5] [--out notes/data_inspection.md]
"""

import argparse
import hashlib
import os
import sys
from datetime import datetime, timezone

import h5py
import numpy as np

DEFAULT_PATH = "data/raw/2D_DarcyFlow_beta1.0_Train.hdf5"
CHUNK = 500          # samples per read
MAX_UNIQUE_SHOW = 20  # how many distinct values to list explicitly


def fmt(x):
    return f"{x:.6g}"


def summarize_dataset(name, ds, lines):
    lines.append(f"### `{name}`")
    lines.append(f"- shape: `{ds.shape}`, dtype: `{ds.dtype}`, chunks: `{ds.chunks}`, "
                 f"compression: `{ds.compression}`")
    for k, v in ds.attrs.items():
        lines.append(f"- attr `{k}`: `{v!r}`")
    if ds.size == 0 or not np.issubdtype(ds.dtype, np.number):
        lines.append("")
        return

    # Small arrays (e.g. coordinates): read whole thing.
    if ds.ndim <= 1 or ds.shape[0] <= 1 or ds.size <= 10_000:
        a = ds[()]
        lines.append(f"- min {fmt(a.min())}, max {fmt(a.max())}, mean {fmt(a.mean())}, std {fmt(a.std())}")
        if ds.ndim == 1:
            d = np.diff(a)
            lines.append(f"- first 3: {[fmt(v) for v in a[:3]]}, last 3: {[fmt(v) for v in a[-3:]]}")
            if d.size:
                lines.append(f"- spacing: min {fmt(d.min())}, max {fmt(d.max())} "
                             f"(uniform: {bool(np.allclose(d, d[0]))})")
        lines.append("")
        return

    # Large arrays: chunked pass over the first (sample) axis.
    n = ds.shape[0]
    gmin, gmax = np.inf, -np.inf
    s, s2, count = 0.0, 0.0, 0
    n_nan = n_inf = 0
    uniq = set()
    uniq_overflow = False
    per_sample_unique = []
    per_sample_min, per_sample_max = [], []
    for i in range(0, n, CHUNK):
        a = ds[i:i + CHUNK].astype(np.float64)
        n_nan += int(np.isnan(a).sum())
        n_inf += int(np.isinf(a).sum())
        f = a[np.isfinite(a)]
        gmin, gmax = min(gmin, f.min()), max(gmax, f.max())
        s += f.sum(); s2 += (f ** 2).sum(); count += f.size
        flat = a.reshape(a.shape[0], -1)
        per_sample_min.extend(flat.min(axis=1)); per_sample_max.extend(flat.max(axis=1))
        for row in flat:
            u = np.unique(row)
            per_sample_unique.append(u.size)
            if not uniq_overflow:
                uniq.update(u.tolist())
                if len(uniq) > 100_000:
                    uniq_overflow = True
    mean = s / count
    std = np.sqrt(max(s2 / count - mean ** 2, 0.0))
    psu = np.array(per_sample_unique)
    lines.append(f"- min {fmt(gmin)}, max {fmt(gmax)}, mean {fmt(mean)}, std {fmt(std)}")
    lines.append(f"- NaN count {n_nan}, Inf count {n_inf}")
    lines.append(f"- per-sample min: range [{fmt(min(per_sample_min))}, {fmt(max(per_sample_min))}]; "
                 f"per-sample max: range [{fmt(min(per_sample_max))}, {fmt(max(per_sample_max))}]")
    if uniq_overflow:
        lines.append("- distinct values overall: > 100,000 (continuous-valued)")
    else:
        u = sorted(uniq)
        shown = ", ".join(fmt(v) for v in u[:MAX_UNIQUE_SHOW])
        more = "" if len(u) <= MAX_UNIQUE_SHOW else f", ... (+{len(u) - MAX_UNIQUE_SHOW} more)"
        lines.append(f"- distinct values overall: {len(u)} -> [{shown}{more}]")
    vals, cnts = np.unique(psu, return_counts=True)
    if vals.size <= 10:
        dist = ", ".join(f"{v} distinct: {c} samples" for v, c in zip(vals, cnts))
    else:
        dist = (f"min {psu.min()}, median {int(np.median(psu))}, max {psu.max()} "
                f"({vals.size} different counts)")
    lines.append(f"- distinct values per sample: {dist}")
    lines.append("")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("path", nargs="?", default=DEFAULT_PATH)
    p.add_argument("--out", default="notes/data_inspection.md")
    p.add_argument("--no-md5", action="store_true")
    args = p.parse_args()

    lines = ["# Data inspection: PDEBench 2D Darcy flow (beta = 1.0)", ""]
    lines.append(f"- file: `{args.path}`")
    lines.append(f"- size: {os.path.getsize(args.path):,} bytes")
    if not args.no_md5:
        h = hashlib.md5()
        with open(args.path, "rb") as fh:
            for block in iter(lambda: fh.read(1 << 24), b""):
                h.update(block)
        lines.append(f"- MD5: `{h.hexdigest()}`")
    lines.append(f"- generated by `scripts/inspect_data.py` at "
                 f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
    lines.append("")

    with h5py.File(args.path, "r") as f:
        lines.append("## File-level attributes")
        lines.extend([f"- `{k}`: `{v!r}`" for k, v in f.attrs.items()] or ["- (none)"])
        lines.append("")
        lines.append("## Tree")
        tree = []
        f.visititems(lambda n, o: tree.append(
            f"- `{n}`: " + (f"dataset {o.shape} {o.dtype}" if isinstance(o, h5py.Dataset) else "group")))
        lines.extend(tree)
        lines.append("")
        lines.append("## Datasets")
        datasets = []
        f.visititems(lambda n, o: datasets.append(n) if isinstance(o, h5py.Dataset) else None)
        for name in datasets:
            print(f"inspecting {name} ...", file=sys.stderr)
            summarize_dataset(name, f[name], lines)

    text = "\n".join(lines)
    print(text)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as fh:
        fh.write(text + "\n")
    print(f"\nwrote {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
